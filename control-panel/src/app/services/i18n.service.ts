@Injectable({ providedIn: 'root' })
export class I18nService {
  private lang$ = new BehaviorSubject<Lang>(this.detectInitial());

  get current() {
    return this.lang$.value;
  }

  langChanges() {
    return this.lang$.asObservable();
  }

  toggleLanguage(): void {
    const next: Lang = this.current === 'en' ? 'es' : 'en';
    this.setLanguage(next);
  }

  setLanguage(lang: Lang): void {
    this.lang$.next(lang);
    try {
      localStorage.setItem('mereka:lang', lang);
    } catch (e) {
      // ignore
    }
  }

  t(key: string): string {
    const lang = this.current;
    return TRANSLATIONS[lang][key] ?? TRANSLATIONS['en'][key] ?? key;
  }

  private detectInitial(): Lang {
    try {
      const stored = localStorage.getItem('mereka:lang') as Lang | null;
      if (stored === 'en' || stored === 'es') return stored;
    } catch (e) {
      // ignore
    }
    return 'en';
  }
}
